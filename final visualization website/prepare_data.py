"""
prepare_data.py — aggregates airport_weather_monthly.csv into data.js
Run from the rosa/ folder (or update DATA_PATH). Output: data.js
"""
import pandas as pd
import json

DATA_PATH = '../data/airport_weather_monthly.csv'   # adjust if needed

df = pd.read_csv(DATA_PATH, low_memory=False)
for col in ['arr_flights','arr_del15','carrier_ct','weather_ct','nas_ct',
            'security_ct','late_aircraft_ct','airport_latitude','airport_longitude',
            'noaa_PRCP','noaa_TAVG']:
    df[col] = pd.to_numeric(df[col], errors='coerce')

agg = df.groupby(['airport','airport_name','airport_latitude','airport_longitude']).agg({
    'arr_flights':'sum','arr_del15':'sum',
    'carrier_ct':'sum','weather_ct':'sum','nas_ct':'sum',
    'security_ct':'sum','late_aircraft_ct':'sum',
    'noaa_PRCP':'mean','noaa_TAVG':'mean'}).reset_index()

agg['delay_rate'] = agg['arr_del15'] / agg['arr_flights']
agg['total_causes'] = agg[['carrier_ct','weather_ct','nas_ct','security_ct','late_aircraft_ct']].sum(axis=1)
for c in ['carrier_ct','weather_ct','nas_ct','security_ct','late_aircraft_ct']:
    agg[f'{c}_pct'] = agg[c] / agg['total_causes'] * 100

out = agg.rename(columns={
    'airport_name':'name','airport_latitude':'lat','airport_longitude':'lon',
    'arr_flights':'flights','delay_rate':'delay','noaa_PRCP':'prcp','noaa_TAVG':'temp',
    'carrier_ct_pct':'carrier','weather_ct_pct':'weather','nas_ct_pct':'nas',
    'security_ct_pct':'security','late_aircraft_ct_pct':'late'})
keep = ['airport','name','lat','lon','flights','delay','weather','prcp','temp',
        'carrier','nas','security','late']
out = out[keep]
out['delay'] = (out['delay']*100).round(2)
for c in ['weather','carrier','nas','security','late']:
    out[c] = out[c].round(1)
out['prcp'] = out['prcp'].round(1)
out['temp'] = out['temp'].round(1)
out['flights'] = out['flights'].round().astype(int)
out = out.where(pd.notna(out), None)

t10 = agg.nlargest(10,'arr_flights')[['airport','arr_flights',
    'carrier_ct_pct','weather_ct_pct','nas_ct_pct','security_ct_pct','late_aircraft_ct_pct']].rename(
    columns={'arr_flights':'flights','carrier_ct_pct':'carrier','weather_ct_pct':'weather',
             'nas_ct_pct':'nas','security_ct_pct':'security','late_aircraft_ct_pct':'late'})
for c in ['carrier','weather','nas','security','late']:
    t10[c] = t10[c].round(1)
t10['flights'] = t10['flights'].round().astype(int)

js = "// AUTO-GENERATED by prepare_data.py — do not edit by hand\n"
js += "const AIRPORT_DATA = " + json.dumps(out.to_dict('records')) + ";\n\n"
js += "const TOP10_DATA = " + json.dumps(t10.to_dict('records')) + ";\n"
open('data.js','w').write(js)
print(f"data.js written: {len(out)} airports, {len(t10)} top-10")